#!/usr/bin/env bash
# Assemble a CUDA toolkit in your home directory from NVIDIA's pip wheels —
# no root, no system CUDA install — so `cargo build --features cuda` works on a
# machine that has only the NVIDIA *driver*. POC dev aid; not used by CI.
#
# Usage: ./scripts/cuda-userspace-toolkit.sh [dest-dir]      (default ~/.local/cuda-<ver>-pip)
#   then: source <dest-dir>/env.sh && cargo build --release --features cuda
#
# Pick a toolkit version <= the "CUDA Version" `nvidia-smi` prints: PTX built by a
# newer toolkit than the driver understands is rejected at run time. Override with
#   CUDA_WHEEL_VERSION=13.2.86 CUBLAS_VERSION=13.2.1.1 CURAND_VERSION=10.4.2.51
# and the GPU's compute capability with CUDA_COMPUTE_CAP (default: read from nvidia-smi).
set -euo pipefail

VER="${CUDA_WHEEL_VERSION:-13.2.86}"
CUBLAS="${CUBLAS_VERSION:-13.2.1.1}"
CURAND="${CURAND_VERSION:-10.4.2.51}"
DEST="${1:-$HOME/.local/cuda-${VER%.*}-pip}"
PIP="${PIP:-python3 -m pip}"
TOOLKIT="$DEST/nvidia/cu13"

if command -v nvidia-smi >/dev/null 2>&1; then
  drv="$(nvidia-smi 2>/dev/null | sed -n 's/.*CUDA Version: *\([0-9.]*\).*/\1/p' | head -1)"
  cap="$(nvidia-smi --query-gpu=compute_cap --format=csv,noheader 2>/dev/null | head -1 | tr -d '. ')"
  echo "driver supports CUDA ${drv:-unknown}; GPU compute capability ${cap:-unknown}; installing toolkit $VER"
fi

mkdir -p "$DEST"
$PIP install --no-deps --upgrade --target "$DEST" \
  "nvidia-cuda-nvcc==$VER" "nvidia-nvvm==$VER" "nvidia-cuda-crt==$VER" \
  "nvidia-cuda-runtime==$VER" "nvidia-cuda-cccl==$VER" "nvidia-cuda-nvrtc==$VER"

# pip refuses to merge two installs into one --target, so fetch these two aside and copy in.
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
$PIP install --no-deps --target "$tmp" "nvidia-cublas==$CUBLAS" "nvidia-curand==$CURAND"
cp -a "$tmp/nvidia/cu13/lib/." "$TOOLKIT/lib/"
cp -an "$tmp/nvidia/cu13/include/." "$TOOLKIT/include/" 2>/dev/null || true

# cudarc links dynamically at build time and asks for the unversioned names.
( cd "$TOOLKIT/lib" && for f in libcublas.so.13 libcublasLt.so.13 libcurand.so.10 libnvrtc.so.13 libcudart.so.13; do
    [ -e "$f" ] && ln -sf "$f" "${f%.so.*}.so"; done )

cat > "$DEST/env.sh" <<ENV
# Generated by scripts/cuda-userspace-toolkit.sh. \`source\` it before building with --features cuda.
export CUDA_HOME="$TOOLKIT"
export CUDA_PATH="\$CUDA_HOME" CUDA_ROOT="\$CUDA_HOME" CUDA_TOOLKIT_ROOT_DIR="\$CUDA_HOME"
export PATH="\$CUDA_HOME/bin:\$PATH"
export LIBRARY_PATH="\$CUDA_HOME/lib:/usr/lib/x86_64-linux-gnu\${LIBRARY_PATH:+:\$LIBRARY_PATH}"
export LD_LIBRARY_PATH="\$CUDA_HOME/lib:/usr/lib/x86_64-linux-gnu\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export CUDA_COMPUTE_CAP="\${CUDA_COMPUTE_CAP:-${CUDA_COMPUTE_CAP:-${cap:-86}}}"
ENV

"$TOOLKIT/bin/nvcc" --version | tail -2
echo "ok: $DEST/env.sh written. Next: source it, then  cargo build --release --features cuda"
